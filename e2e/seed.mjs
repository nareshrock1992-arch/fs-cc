// Migrate and seed the DISPOSABLE e2e database (called by e2e/run.sh).
// Credentials come from the environment (generated per run by run.sh) and are never written to disk.
import { createRequire } from 'node:module';

const need = ['DB_NAME', 'E2E_ADMIN_USER', 'E2E_ADMIN_PASS', 'E2E_AGENT_ID', 'E2E_AGENT_PIN', 'E2E_SUP_PASS'];
for (const k of need) if (!process.env[k]) { console.error(`seed: ${k} missing`); process.exit(1); }
if (!/_e2e$/.test(process.env.DB_NAME)) { console.error('seed: refusing a database not ending in _e2e'); process.exit(1); }

const require = createRequire(new URL('../backend/package.json', import.meta.url));
const bcrypt = require('bcryptjs');
const { runMigrations } = await import('../backend/db/migrationRunner.js');
const { pool } = await import('../backend/db/pool.js');

await runMigrations();
await pool.query(
  `INSERT INTO users (username, password_hash, role) VALUES ($1, $2, 'admin')`,
  [process.env.E2E_ADMIN_USER, await bcrypt.hash(process.env.E2E_ADMIN_PASS, 10)],
);
await pool.query(
  `INSERT INTO agents (agent_id, full_name, avaya_extension, contact, agent_type, pin_hash)
   VALUES ($1, 'E2E Agent', '5999', '{sip_cid_type=pid}user/1999@127.0.0.1', 'internal', $2)`,
  [process.env.E2E_AGENT_ID, await bcrypt.hash(process.env.E2E_AGENT_PIN, 10)],
);
// Supervisors for permission tests: one with no extra rights, one allowed to manage break codes
// and call outcomes. Same per-run password (generated by run.sh).
const supHash = await bcrypt.hash(process.env.E2E_SUP_PASS, 10);
await pool.query(
  `INSERT INTO users (username, password_hash, role, permissions) VALUES
     ('e2e_sup', $1, 'supervisor', '{}'),
     ('e2e_sup_codes', $1, 'supervisor', '{manage_break_codes,manage_dispositions}')`,
  [supHash],
);
await pool.query(
  `INSERT INTO queues (name, display_name) VALUES ('e2e_q@default', 'E2E Queue')`,
);

// M2 service level fixture: queue e2e_sla (target 20 s) with known calls today.
// Expected service level = answered within 20 s / (answered + ALL abandoned) = 3 / (4 + 2) = 50.0 %.
await pool.query(
  `INSERT INTO queues (name, display_name, sla_seconds) VALUES ('e2e_sla@default', 'E2E SLA Queue', 20)`,
);
await pool.query(
  `INSERT INTO agent_tiers (agent_id, queue_id)
   SELECT a.id, q.id FROM agents a, queues q WHERE a.agent_id = $1 AND q.name = 'e2e_sla@default'`,
  [process.env.E2E_AGENT_ID],
);
const calls = [
  // [wait_seconds, disposition, abandoned, ended]
  [5, 'answered', false, true], [10, 'answered', false, true], [20, 'answered', false, true],   // within target (20 s counts)
  [30, 'answered', false, true],                                                              // late
  [3, 'abandoned', true, true], [40, 'abandoned', true, true],                                // both count (owner decision)
  [null, null, false, false],                                                                 // still waiting: not counted
];
for (const [i, [wait, disp, ab, ended]] of calls.entries()) {
  await pool.query(
    `INSERT INTO calls (call_uuid, queue_name, start_time, queue_enter_time, end_time, wait_seconds, abandoned, disposition)
     VALUES ($1, 'e2e_sla@default', now() - interval '10 minutes', now() - interval '10 minutes',
             CASE WHEN $2 THEN now() - interval '5 minutes' END, $3, $4, $5)`,
    [`e2e-sla-${i}`, ended, wait, ab, disp],
  );
}
await pool.end();
console.log('seed: database migrated and seeded');
